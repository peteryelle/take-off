  USING (org_id = auth_org_id())
  WITH CHECK (org_id = auth_org_id());

CREATE TABLE IF NOT EXISTS public.labor_tasks (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  catalog_id bigint NOT NULL REFERENCES parts_catalogs(id),
  org_id bigint NOT NULL REFERENCES organizations(id),
  task_name text NOT NULL,
  section text,
  device_role text,
  hrs_per_unit numeric,
  setup_hrs numeric,
  active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE labor_tasks ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS labor_tasks_tenant_isolation ON labor_tasks;
CREATE POLICY labor_tasks_tenant_isolation ON labor_tasks
  USING (org_id = auth_org_id());

